// SaveUpload persists the authenticated owner's raw upload under the storage
// key registered by CreateMediaAsset. The command state remains UPLOADING;
// CompleteMediaUpload and ProcessMediaAsset still own lifecycle transitions.
func (s *Service) SaveUpload(ctx context.Context, id string, ownerPrincipalID string, source io.Reader, maxBytes int64) (MediaAsset, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.saveUploadLocked(ctx, id, ownerPrincipalID, source, maxBytes)
}

func (s *Service) saveUploadLocked(ctx context.Context, id string, ownerPrincipalID string, source io.Reader, maxBytes int64) (MediaAsset, error) {
	asset, err := s.repository.GetAsset(ctx, id)
	if err != nil {
		return MediaAsset{}, err
	}
	if asset.OwnerPrincipalID != ownerPrincipalID {
		return MediaAsset{}, ErrMediaNotOwner
	}
	if asset.ProcessingStatus != "UPLOADING" {
		return MediaAsset{}, ErrStatusTransition
	}
	key := asset.OriginalStorageKey
	if key == "" || filepath.Base(key) != key || strings.Contains(key, "..") {
		return MediaAsset{}, errors.New("invalid storage key")
	}
	if maxBytes <= 0 {
		maxBytes = 20 << 20
	}
	if err := os.MkdirAll(s.storeDir, 0o750); err != nil {
		return MediaAsset{}, err
	}
	destinationPath := filepath.Join(s.storeDir, key)
	temporary, err := os.CreateTemp(s.storeDir, ".proxy-upload-*")
	if err != nil {
		return MediaAsset{}, err
	}
	temporaryPath := temporary.Name()
	committed := false
	defer func() {
		_ = temporary.Close()
		if !committed {
			_ = os.Remove(temporaryPath)
		}
	}()
	buffered := bufio.NewReader(source)
	header, peekErr := buffered.Peek(512)
	if peekErr != nil && !errors.Is(peekErr, io.EOF) {
		return MediaAsset{}, peekErr
	}
	detectedMime := detectMediaMime(header)
	if !mediaMimeAllowed(asset.MediaType, asset.MimeType, detectedMime) {
		return MediaAsset{}, ErrMediaTypeMismatch
	}
	hasher := sha256.New()
	written, err := io.Copy(io.MultiWriter(temporary, hasher), io.LimitReader(buffered, maxBytes+1))
	if err != nil {
		return MediaAsset{}, err
	}
	if written > maxBytes {
		return MediaAsset{}, ErrUploadTooLarge
	}
	if err := temporary.Sync(); err != nil {
		return MediaAsset{}, err
	}
	if err := temporary.Close(); err != nil {
		return MediaAsset{}, err
	}
	if asset.MediaType == "IMAGE" {
		metadata := readSourceImageMetadata(ctx, temporaryPath, detectedMime)
		if metadata.Width > 0 && metadata.Height > 0 {
			asset.Width = metadata.Width
			asset.Height = metadata.Height
		}
		asset.Orientation = metadata.Orientation
		asset.ColorSpace = metadata.ColorSpace
		asset.HasAlpha = metadata.HasAlpha
		asset.Animated = metadata.Animated
	}
	// Link is exclusive: unlike Rename on Unix it cannot silently overwrite an
	// existing ORIGINAL object. The temp file lives in the same directory/filesystem.
	if err := os.Link(temporaryPath, destinationPath); err != nil {
		if errors.Is(err, os.ErrExist) {
			incomingHash := hex.EncodeToString(hasher.Sum(nil))
			// A PUT whose response was lost may be retried. The exact same bytes
			// are idempotent; different bytes can never replace ORIGINAL.
			if asset.SourceBytes == written && asset.ChecksumSHA256 != "" && asset.ChecksumSHA256 == incomingHash {
				_ = os.Remove(temporaryPath)
				committed = true
				if variantErr := s.persistOriginalVariant(ctx, asset); variantErr != nil {
					return MediaAsset{}, variantErr
				}
				return asset, nil
			}
			return MediaAsset{}, ErrOriginalImmutable
		}
		return MediaAsset{}, err
	}
	originalPersisted := true
	defer func() {
		if originalPersisted {
			_ = os.Remove(destinationPath)
		}
	}()
	asset.SourceBytes = written
	asset.ChecksumSHA256 = hex.EncodeToString(hasher.Sum(nil))
	asset.MimeType = detectedMime
	if err := s.repository.UpdateAsset(ctx, asset, "UPLOADING"); err != nil {
		return MediaAsset{}, err
	}
	originalPersisted = false
	if err := s.persistOriginalVariant(ctx, asset); err != nil {
		return MediaAsset{}, err
	}
	_ = os.Remove(temporaryPath)
	committed = true
	return asset, nil
}

// UploadOffset returns the durable byte boundary for a resumable upload. The
// partial object lives beside the immutable ORIGINAL so an API restart does not
// force the client to resend accepted chunks.
func (s *Service) UploadOffset(ctx context.Context, id, ownerPrincipalID string) (UploadProgress, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	asset, err := s.uploadingAsset(ctx, id, ownerPrincipalID)
	if err != nil {
		return UploadProgress{}, err
	}
	if asset.SourceBytes > 0 {
		return UploadProgress{Offset: asset.SourceBytes, Total: asset.SourceBytes, Complete: true}, nil
	}
	info, err := os.Stat(s.partialUploadPath(asset))
	if errors.Is(err, os.ErrNotExist) {
		return UploadProgress{}, nil
	}
	if err != nil {
		return UploadProgress{}, err
	}
	return UploadProgress{Offset: info.Size()}, nil
}

// SaveUploadChunk appends exactly one Content-Range chunk. A replay of an
// already committed chunk is accepted only when its bytes are identical.
func (s *Service) SaveUploadChunk(ctx context.Context, id, ownerPrincipalID string, source io.Reader, start, end, total, maxBytes int64, expectedSHA256 string) (UploadProgress, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	asset, err := s.uploadingAsset(ctx, id, ownerPrincipalID)
	if err != nil {
		return UploadProgress{}, err
	}
	if start < 0 || end < start || total <= end || total > maxBytes {
		return UploadProgress{}, ErrUploadLength
	}
	expectedBytes := end - start + 1
	chunk, err := io.ReadAll(io.LimitReader(source, expectedBytes+1))
	if err != nil {
		return UploadProgress{}, err
	}
	if int64(len(chunk)) != expectedBytes {
		return UploadProgress{}, ErrUploadLength
	}
	hash := sha256.Sum256(chunk)
	if expectedSHA256 == "" || !strings.EqualFold(expectedSHA256, hex.EncodeToString(hash[:])) {
		return UploadProgress{}, ErrChunkChecksum
	}
	if err := os.MkdirAll(s.storeDir, 0o750); err != nil {
		return UploadProgress{}, err
	}
	partialPath := s.partialUploadPath(asset)
	file, err := os.OpenFile(partialPath, os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return UploadProgress{}, err
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil {
		return UploadProgress{}, err
	}
	current := info.Size()
	if start < current {
		if end+1 > current {
			return UploadProgress{Offset: current, Total: total}, ErrUploadOffset
		}
		existing := make([]byte, len(chunk))
		if _, err := file.ReadAt(existing, start); err != nil || !bytes.Equal(existing, chunk) {
			return UploadProgress{Offset: current, Total: total}, ErrChunkChecksum
		}
		return UploadProgress{Offset: current, Total: total, Complete: current == total}, nil
	}
	if start != current {
		return UploadProgress{Offset: current, Total: total}, ErrUploadOffset
	}
	if _, err := file.WriteAt(chunk, start); err != nil {
		return UploadProgress{}, err
	}
	if err := file.Sync(); err != nil {
		return UploadProgress{}, err
	}
	current = end + 1
	if current < total {
		return UploadProgress{Offset: current, Total: total}, nil
	}
	if err := file.Close(); err != nil {
		return UploadProgress{}, err
	}
	assembled, err := os.Open(partialPath)
	if err != nil {
		return UploadProgress{}, err
	}
	_, saveErr := s.saveUploadLocked(ctx, id, ownerPrincipalID, assembled, maxBytes)
	closeErr := assembled.Close()
	if saveErr != nil {
		return UploadProgress{}, saveErr
	}
	if closeErr != nil {
		return UploadProgress{}, closeErr
	}
	if err := os.Remove(partialPath); err != nil && !errors.Is(err, os.ErrNotExist) {
		return UploadProgress{}, err
	}
	return UploadProgress{Offset: total, Total: total, Complete: true}, nil
}

func (s *Service) uploadingAsset(ctx context.Context, id, ownerPrincipalID string) (MediaAsset, error) {
	asset, err := s.repository.GetAsset(ctx, id)
	if err != nil {
		return MediaAsset{}, err
	}
	if asset.OwnerPrincipalID != ownerPrincipalID {
		return MediaAsset{}, ErrMediaNotOwner
	}
	if asset.ProcessingStatus != "UPLOADING" {
		return MediaAsset{}, ErrStatusTransition
	}
	if asset.OriginalStorageKey == "" || filepath.Base(asset.OriginalStorageKey) != asset.OriginalStorageKey || strings.Contains(asset.OriginalStorageKey, "..") {
		return MediaAsset{}, errors.New("invalid storage key")
	}
	return asset, nil
}

func (s *Service) partialUploadPath(asset MediaAsset) string {
	return filepath.Join(s.storeDir, "."+asset.MediaAssetID+"."+asset.OriginalStorageKey+".part")
}

func (s *Service) persistOriginalVariant(ctx context.Context, asset MediaAsset) error {
	now := s.clock.Now().UTC()
	return s.repository.UpsertVariant(ctx, MediaVariant{
		MediaVariantID: "mv_" + asset.MediaAssetID + "_original_v1",
		MediaAssetID:   asset.MediaAssetID,
		Purpose:        "ORIGINAL",
		RecipeVersion:  "original_v1",
		Format:         asset.MimeType,
		Width:          asset.Width,
		Height:         asset.Height,
		Bytes:          asset.SourceBytes,
		StorageKey:     asset.OriginalStorageKey,
		ContentHash:    asset.ChecksumSHA256,
		Status:         "READY",
		CreatedAt:      now,
		UpdatedAt:      now,
	})
}

func detectMediaMime(header []byte) string {
	if len(header) >= 12 && string(header[4:8]) == "ftyp" {
		brand := string(header[8:12])
		switch brand {
		case "heic", "heix", "hevc", "hevx", "mif1", "msf1":
			return "image/heic"
		case "avif", "avis":
			return "image/avif"
		}
	}
	return http.DetectContentType(header)
}

func mediaMimeAllowed(mediaType, declared, detected string) bool {
	expectedPrefix := "image/"
	switch mediaType {
	case "VIDEO":
		expectedPrefix = "video/"
	case "AUDIO":
		// 录音产物是 m4a/mp4 容器，http.DetectContentType 探测为 video/mp4；
		// 只要求声明类型以 audio/ 开头且探测结果不是图片即可，精确校验交给 ffprobe。
		normalizedDeclared := strings.ToLower(strings.TrimSpace(strings.Split(declared, ";")[0]))
		return strings.HasPrefix(normalizedDeclared, "audio/") && !strings.HasPrefix(detected, "image/")
	}
	if !strings.HasPrefix(detected, expectedPrefix) {
		return false
	}
	normalize := func(value string) string {
		value = strings.ToLower(strings.TrimSpace(strings.Split(value, ";")[0]))
		if value == "image/jpg" {
			return "image/jpeg"
		}
		if value == "image/heif" {
			return "image/heic"
		}
		return value
	}
	return declared == "" || normalize(declared) == normalize(detected)
}

// ResolveServingPath 把 READY 资产的 storage key 解析为本地文件路径，供
// GET /v1/media/play|thumb/{id} 直接 ServeFile（客户端播 MP4/图片 URL）。
// kind: "play" | "thumb"（thumb 缺失时降级回 playback 文件）。
// fail-closed：非 READY / key 含路径分隔符（防目录穿越）一律拒绝。
func (s *Service) ResolveServingPath(ctx context.Context, id string, kind string) (string, error) {
	asset, err := s.repository.GetAsset(ctx, id)
	if err != nil {
		return "", err
	}
	if asset.ProcessingStatus != "READY" {
		return "", errors.New("media not ready")
	}
	if asset.ModerationStatus != "APPROVED" || asset.VisibilityClass != "PUBLIC" {
		return "", errors.New("media is not publicly deliverable")
	}
	key := asset.PlaybackStorageKey
	if kind == "thumb" {
		if asset.ThumbnailStorageKey != "" {
			key = asset.ThumbnailStorageKey
		}
	}
	if key == "" || strings.ContainsAny(key, "/\\") || strings.Contains(key, "..") {
		return "", errors.New("invalid storage key")
	}
	return filepath.Join(s.storeDir, key), nil
}

func (s *Service) ResolveVariantPath(ctx context.Context, variantID string) (string, error) {
	variant, err := s.repository.GetVariant(ctx, variantID)
	if err != nil {
		return "", err
	}
	if variant.Status != "READY" {
		return "", errors.New("variant not ready")
	}
	if variant.Purpose == "ORIGINAL" {
		return "", errors.New("original variant is not a public delivery resource")
	}
	asset, err := s.repository.GetAsset(ctx, variant.MediaAssetID)
	if err != nil {
		return "", err
	}
	if asset.ProcessingStatus != "READY" || asset.ModerationStatus != "APPROVED" || asset.VisibilityClass != "PUBLIC" {
		return "", errors.New("variant is not publicly deliverable")
	}
	if variant.StorageKey == "" || strings.ContainsAny(variant.StorageKey, "/\\") || strings.Contains(variant.StorageKey, "..") {
		return "", errors.New("invalid variant storage key")
	}
	return filepath.Join(s.storeDir, variant.StorageKey), nil
}

func (s *Service) ListReadyVariants(ctx context.Context, mediaAssetID string) ([]MediaVariant, error) {
	variants, err := s.repository.ListVariants(ctx, mediaAssetID)
	if err != nil {
		return nil, err
	}
	ready := make([]MediaVariant, 0, len(variants))
	for _, variant := range variants {
		if variant.Status == "READY" {
			ready = append(ready, variant)
		}
	}
	return ready, nil
}

// AuthorizeForStorefront promotes technically approved media uploads to
// PUBLIC so store album and menu photos are remotely viewable (thumb/play
// URLs). Storefronts are public surfaces; same trust shape as posts.
func (s *Service) AuthorizeForStorefront(ctx context.Context, ids []string, ownerPrincipalID string) error {
	return s.AuthorizeForPost(ctx, ids, ownerPrincipalID, "PUBLIC")
}

// AuthorizeForPost is the server-owned publication transition. READY alone is
// never public: only the owner can attach technically approved media, and the
// asset receives exactly the Post visibility class inside the command transaction.
func (s *Service) AuthorizeForPost(ctx context.Context, ids []string, ownerPrincipalID, visibility string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if visibility != "PUBLIC" && visibility != "FOLLOWERS" && visibility != "AGENT_ONLY" {
		return errors.New("unsupported media visibility")
	}
	for _, id := range ids {
		asset, err := s.repository.GetAsset(ctx, id)
		if err != nil {
			return err
		}
		if asset.OwnerPrincipalID != ownerPrincipalID {
			return ErrMediaNotOwner
		}
		if asset.ProcessingStatus != "READY" || asset.ModerationStatus != "APPROVED" {
			return ErrStatusTransition
		}
		if asset.VisibilityClass != "OWNER_ONLY" && asset.VisibilityClass != visibility {
			return errors.New("media already bound to another visibility class")
		}
		if asset.VisibilityClass == visibility {
			continue
		}
		asset.VisibilityClass = visibility
		asset.UpdatedAt = s.clock.Now().UTC()
		if err := s.repository.UpdateAsset(ctx, asset, "READY"); err != nil {
			return err
		}
	}
	return nil
}

func (s *Service) Supports(commandType string) bool {
	switch commandType {
	case "CreateMediaAsset", "CompleteMediaUpload", "ProcessMediaAsset",
		"MarkMediaReady", "GetMediaAsset", "ListMediaAssets",
		// R15.17: admin review command — media 域接手 dispatch。
		"ReviewMediaAsset":
		return true
	default:
		return false
	}
}

func (s *Service) Handle(e command.Envelope) command.Result {
	return s.HandleContext(context.Background(), e)
}

func (s *Service) HandleContext(ctx context.Context, e command.Envelope) command.Result {
	s.mu.Lock()
	defer s.mu.Unlock()
	switch e.CommandType {
	case "CreateMediaAsset":
		return s.createAsset(ctx, e)
	case "CompleteMediaUpload":
		return s.completeUpload(ctx, e)
	case "ProcessMediaAsset":
		return s.processAsset(ctx, e)
	case "MarkMediaReady":
		return s.markReady(ctx, e)
	case "GetMediaAsset":
		return s.getAsset(ctx, e)
	case "ListMediaAssets":
		return s.listAssets(ctx, e)
	// R15.17: admin 手动 content review 路径。仅 operator (PROXY_OPERATOR_PRINCIPALS)
	// 可调用。ReviewMediaAsset 只能把 asset 从 QUARANTINED/APPROVED
	// 过渡到 REJECTED_CONTENT_NUDITY / _POLITICS / _VIOLENCE, 或
	// 从任一状态返回 APPROVED (unblock)。
	case "ReviewMediaAsset":
		return s.reviewMediaAsset(ctx, e)
	// R15.18: audit 列表 — operator 查 content review 决策历史。
	// 逻辑: operator in PROXY_OPERATOR_PRINCIPALS (server 门已验)
	// 看到所有 asset 的决策行,不能只看到自己作为 operator 的。
	// 按 mediaAssetId 过滤 (空 = 所有),按 reviewedAt 倒序。
	case "ListMediaReviewDecisions":
		return s.listMediaReviewDecisions(ctx, e)
	// R15.19: 修订决策 (append-only 加修订行)。amends 语义, 不改 prev
	// 行的 from/to/reason/operator — 只多 1 行 note="amends:<prev_id>:<reason>:<note>"
	// 钉审计历史。
	case "AmendMediaReviewDecision":
		return s.amendMediaReviewDecision(ctx, e)
	default:
		return command.Rejected(e, "MEDIA_COMMAND_UNSUPPORTED", "VALIDATION", "AFTER_USER_ACTION", "media.unsupported_command", nil)
	}
}

// ---------- CreateMediaAsset ----------
// 登记上传：拿到 upload URL（dev 返回本地直传路径），资产 = UPLOADING。

type createAssetPayload struct {
	MediaType          string `json:"mediaType"`
	OriginalStorageKey string `json:"originalStorageKey"`
	MimeType           string `json:"mimeType"`
	Width              int    `json:"width"`
	Height             int    `json:"height"`
	// R16.7-P1-K (LC-06) + R16.7-P1-I (LC-07): AI generation
	// provenance. Optional at CreateMediaAsset; the asset
	// is registered with source=USER_UPLOADED by default. AI
	// uploads (PersonaID set) are accepted as well; the
	// MarkMediaReady handler is the gate that enforces the
	// fail-closed behaviour.
	AIGenerationSource string `json:"aiGenerationSource,omitempty"`
	PersonaID          string `json:"personaId,omitempty"`
	SubjectID          string `json:"subjectId,omitempty"`
}

func (s *Service) createAsset(ctx context.Context, e command.Envelope) command.Result {
	var p createAssetPayload
	if !decode(e.Payload, &p) || p.MediaType == "" || p.OriginalStorageKey == "" {
		return command.Rejected(e, "INVALID_MEDIA_ASSET", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_asset", nil)
	}
	if p.MediaType != "IMAGE" && p.MediaType != "VIDEO" && p.MediaType != "AUDIO" {
		return command.Rejected(e, "INVALID_MEDIA_TYPE", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_type", map[string]any{"mediaType": p.MediaType})
	}
	// R16.7-P1-K (LC-06): normalize the AI source at the
	// boundary. Empty input defaults to USER_UPLOADED — that
	// is the only safe assumption (a user uploading a phone
	// photo cannot accidentally be tagged as AI). Unknown
	// non-empty values are rejected so the producer must
	// commit to a known source.
	aiSource := normalizeAIGenerationSource(p.AIGenerationSource)
	if p.AIGenerationSource != "" && aiSource == "UNKNOWN" {
		return command.Rejected(e, "INVALID_AI_GENERATION_SOURCE", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_ai_source", map[string]any{"aiGenerationSource": p.AIGenerationSource})
	}
	// R16.7-P1-I (LC-07): when the asset is AI_PERSONA, the
	// persona id is required so the likeness-consent lookup
	// at MarkMediaReady has a target. SubjectID is also
	// required for USER_TWIN personas; the catalogue has it
	// on the persona row, but we accept it inline for the
	// simple case (one persona, one subject).
	if aiSource == "AI_PERSONA" && p.PersonaID == "" {
		return command.Rejected(e, "AI_PERSONA_ID_REQUIRED", "VALIDATION", "AFTER_USER_ACTION", "media.ai_persona_id_required", nil)
	}
	if aiSource == "AI_PERSONA" && p.PersonaID != "" && p.SubjectID == "" {
		// SubjectID is optional at create time; the media
		// service falls back to the asset's owner principal
		// at MarkMediaReady. This is the common case: the
		// user is uploading their own likeness.
		p.SubjectID = e.Principal.ID
	}
	now := s.clock.Now().UTC()
	asset := MediaAsset{
		MediaAssetID:       newID("ma_"),
		OwnerPrincipalType: e.Principal.Type,
		OwnerPrincipalID:   e.Principal.ID,
		MediaType:          p.MediaType,
		OriginalStorageKey: p.OriginalStorageKey,
		MimeType:           p.MimeType,
		Width:              p.Width,
		Height:             p.Height,
		ModerationStatus:   "QUARANTINED",
		VisibilityClass:    "OWNER_ONLY",
		ProcessingStatus:   "UPLOADING",
		CreatedAt:          now,
		UpdatedAt:          now,
		AIGenerationSource: aiSource,
		AIGenerated:        aiSource != "" && aiSource != "USER_UPLOADED",
		PersonaID:          p.PersonaID,
		SubjectID:          p.SubjectID,
	}
	domainEvents := []event.DomainEvent{event.New("MediaAssetCreated", "MediaAsset", asset.MediaAssetID, 1, e.Principal.ID, e.CorrelationID, e.CommandID, now, map[string]any{
		"mediaType": p.MediaType,
		"status":    "UPLOADING",
	})}
	if err := s.repository.CreateAsset(ctx, asset); err != nil {
		return command.Rejected(e, "MEDIA_CREATE_FAILED", "INTERNAL", "SAFE_RETRY", "media.create_failed", nil)
	}
	return acceptedWithPayload(e, "MediaAsset", asset.MediaAssetID, 1, "UPLOADING", map[string]any{
		"mediaAssetId": asset.MediaAssetID,
		"uploadUrl":    "/v1/media/upload/" + asset.MediaAssetID, // dev：本地直传端点
		"status":       "UPLOADING",
	}, domainEvents)
}

// ---------- CompleteMediaUpload ----------
// 上传完成 → PROCESSING（准备处理）。

type completeUploadPayload struct {
	OriginalStorageKey string `json:"originalStorageKey"`
}

func (s *Service) completeUpload(ctx context.Context, e command.Envelope) command.Result {
	var p completeUploadPayload
	if !decode(e.Payload, &p) || p.OriginalStorageKey == "" {
		return command.Rejected(e, "INVALID_COMPLETE_UPLOAD", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_complete_upload", nil)
	}
	asset, err := s.repository.GetAsset(ctx, e.Target.ID)
	if errors.Is(err, ErrAssetNotFound) {
		return command.Rejected(e, "MEDIA_ASSET_NOT_FOUND", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.asset_not_found", nil)
	}
	if err != nil {
		return command.Rejected(e, "MEDIA_READ_FAILED", "INTERNAL", "SAFE_RETRY", "media.read_failed", nil)
	}
	if asset.OwnerPrincipalID != e.Principal.ID {
		return command.Rejected(e, "MEDIA_NOT_OWNER", "AUTHORIZATION", "AFTER_USER_ACTION", "media.not_owner", nil)
	}
	if asset.ProcessingStatus != "UPLOADING" {
		return command.Rejected(e, "MEDIA_NOT_UPLOADING", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.not_uploading", map[string]any{"status": asset.ProcessingStatus})
	}
	if asset.OriginalStorageKey != p.OriginalStorageKey {
		return command.Rejected(e, "STORAGE_KEY_MISMATCH", "VALIDATION", "AFTER_USER_ACTION", "media.storage_key_mismatch", nil)
	}
	asset.ProcessingStatus = "PROCESSING"
	asset.UpdatedAt = s.clock.Now().UTC()
	domainEvents := []event.DomainEvent{event.New("MediaUploadCompleted", "MediaAsset", asset.MediaAssetID, 1, e.Principal.ID, e.CorrelationID, e.CommandID, asset.UpdatedAt, map[string]any{
		"status": "PROCESSING",
	})}
	if err := s.repository.UpdateAsset(ctx, asset, "UPLOADING"); err != nil {
		return command.Rejected(e, "MEDIA_UPDATE_FAILED", "INTERNAL", "SAFE_RETRY", "media.update_failed", nil)
	}
	if err := s.repository.EnqueueProcessingJob(ctx, processingJobFor(asset, asset.UpdatedAt)); err != nil {
		return command.Rejected(e, "MEDIA_JOB_ENQUEUE_FAILED", "INTERNAL", "SAFE_RETRY", "media.job_enqueue_failed", nil)
	}
	return command.Accepted(e, "MediaAsset", asset.MediaAssetID, 1, "PROCESSING", eventRefs(domainEvents))
}

// ---------- ProcessMediaAsset ----------
// Compatibility command: processing is always performed by the durable worker.
// Calling this command only confirms/repairs the idempotent queue entry; it
// never runs ffmpeg in the API request thread.

type processPayload struct {
	OriginalPath string `json:"originalPath"` // dev：本地原文件路径（模拟 Object Storage 取回）
}

func (s *Service) processAsset(ctx context.Context, e command.Envelope) command.Result {
	var p processPayload
	if !decode(e.Payload, &p) {
		return command.Rejected(e, "INVALID_PROCESS_REQUEST", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_process", nil)
	}
	// ffmpeg 支持 http:// / concat: / subfile: 等协议输入：客户端可控路径不做
	// 收敛会变成任意文件读取 + SSRF。只接受本地普通文件路径。
	if p.OriginalPath != "" && !isSafeLocalPath(p.OriginalPath) {
		return command.Rejected(e, "UNSAFE_MEDIA_PATH", "VALIDATION", "AFTER_USER_ACTION", "media.unsafe_path", nil)
	}
	asset, err := s.repository.GetAsset(ctx, e.Target.ID)
	if errors.Is(err, ErrAssetNotFound) {
		return command.Rejected(e, "MEDIA_ASSET_NOT_FOUND", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.asset_not_found", nil)
	}
	if err != nil {
		return command.Rejected(e, "MEDIA_READ_FAILED", "INTERNAL", "SAFE_RETRY", "media.read_failed", nil)
	}
	if asset.OwnerPrincipalID != e.Principal.ID {
		return command.Rejected(e, "MEDIA_NOT_OWNER", "AUTHORIZATION", "AFTER_USER_ACTION", "media.not_owner", nil)
	}
	if asset.ProcessingStatus != "PROCESSING" {
		return command.Rejected(e, "MEDIA_NOT_PROCESSING", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.not_processing", map[string]any{"status": asset.ProcessingStatus})
	}
	if err := s.repository.EnqueueProcessingJob(ctx, processingJobFor(asset, s.clock.Now().UTC())); err != nil {
		return command.Rejected(e, "MEDIA_JOB_ENQUEUE_FAILED", "INTERNAL", "SAFE_RETRY", "media.job_enqueue_failed", nil)
	}
	return acceptedWithPayload(e, "MediaAsset", asset.MediaAssetID, 1, "PROCESSING", map[string]any{
		"mediaAssetId": asset.MediaAssetID, "processingStatus": "PROCESSING",
	}, nil)
}

// ---------- MarkMediaReady ----------
// 手动标 READY（外部 worker 已处理完的场景）。API 边界已将其限定为 operator
// 命令；这里仍坚持 PROCESSING 前置，禁止从 UPLOADING 直接跳过处理链。

type markReadyPayload struct {
	PlaybackStorageKey  string `json:"playbackStorageKey"`
	ThumbnailStorageKey string `json:"thumbnailStorageKey"`
	DurationMs          int64  `json:"durationMs"`
	Width               int    `json:"width"`
	Height              int    `json:"height"`
	Codec               string `json:"codec"`
}

func (s *Service) markReady(ctx context.Context, e command.Envelope) command.Result {
	var p markReadyPayload
	if !decode(e.Payload, &p) {
		return command.Rejected(e, "INVALID_MARK_READY", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_mark_ready", nil)
	}
	asset, err := s.repository.GetAsset(ctx, e.Target.ID)
	if errors.Is(err, ErrAssetNotFound) {
		return command.Rejected(e, "MEDIA_ASSET_NOT_FOUND", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.asset_not_found", nil)
	}
	if err != nil {
		return command.Rejected(e, "MEDIA_READ_FAILED", "INTERNAL", "SAFE_RETRY", "media.read_failed", nil)
	}
	expectedStatus := asset.ProcessingStatus
	if expectedStatus != "PROCESSING" {
		return command.Rejected(e, "MEDIA_NOT_PROCESSABLE", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.not_processable", map[string]any{"status": asset.ProcessingStatus})
	}
	// R16.7-P1-K (LC-06) fail-closed gate: an asset whose
	// AIGenerationSource is UNKNOWN cannot be promoted to
	// READY. The producer must re-declare the source. This is
	// the practical shape of 'fail closed when the AI label
	// cannot be produced' (Vietnam 134/2025/QH15 Art. 12):
	// the platform never publishes unlabeled media, even
	// when the asset looks ready. We do not auto-reject on
	// USER_UPLOADED — the absence of an AI label is
	// meaningful there, not a missing label.
	if asset.AIGenerationSource == "UNKNOWN" {
		return command.Rejected(e, "AI_LABEL_MISSING", "VALIDATION", "AFTER_USER_ACTION", "media.ai_label_missing", map[string]any{"mediaAssetId": asset.MediaAssetID})
	}
	// R16.7-P1-I (LC-07) fail-closed gate: an AI_PERSONA
	// asset must have a live likeness consent for the
	// (persona, subject) tuple. We resolve SubjectID against
	// the asset's subject field first, then fall back to the
	// owner. The check is only enforced when the persona
	// service is wired; the legacy test path skips the
	// consent check so the existing test suite keeps
	// passing. Production deployments must wire it.
	if asset.AIGenerationSource == "AI_PERSONA" && asset.PersonaID != "" && s.personaService != nil {
		subject := asset.SubjectID
		if subject == "" {
			subject = asset.OwnerPrincipalID
		}
		persona, perr := s.personaService.GetPersona(ctx, asset.PersonaID)
		if perr != nil {
			return command.Rejected(e, "AI_PERSONA_NOT_FOUND", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.ai_persona_not_found", map[string]any{"personaId": asset.PersonaID})
		}
		// CREATIVE personas have no real-person likeness;
		// the consent gate is for USER_TWIN only.
		if persona.PersonaType == aipersona.PersonaTypeUserTwin {
			consent, cerr := s.personaService.HasLiveConsent(ctx, asset.PersonaID, subject)
			if cerr != nil {
				return command.Rejected(e, "AI_LIKENESS_CONSENT_LOOKUP_FAILED", "INTERNAL", "SAFE_RETRY", "media.likeness_consent_lookup_failed", map[string]any{"personaId": asset.PersonaID, "subjectId": subject, "error": cerr.Error()})
			}
			if consent == nil {
				return command.Rejected(e, "AI_LIKENESS_CONSENT_MISSING", "VALIDATION", "AFTER_USER_ACTION", "media.likeness_consent_missing", map[string]any{"personaId": asset.PersonaID, "subjectId": subject, "personaType": string(persona.PersonaType)})
			}
			asset.LikenessConsentID = consent.ID
		}
	}
	asset.ProcessingStatus = "READY"
	if p.PlaybackStorageKey != "" {
		asset.PlaybackStorageKey = p.PlaybackStorageKey
	}
	if p.ThumbnailStorageKey != "" {
		asset.ThumbnailStorageKey = p.ThumbnailStorageKey
	}
	asset.DurationMs = p.DurationMs
	asset.Width = p.Width
	asset.Height = p.Height
	asset.Codec = p.Codec
	asset.PlaybackURL = "/v1/media/play/" + asset.MediaAssetID
	asset.ThumbnailURL = "/v1/media/thumb/" + asset.MediaAssetID
	asset.UpdatedAt = s.clock.Now().UTC()
	domainEvents := []event.DomainEvent{event.New("MediaAssetReady", "MediaAsset", asset.MediaAssetID, 1, e.Principal.ID, e.CorrelationID, e.CommandID, asset.UpdatedAt, map[string]any{
		"status": "READY", "mediaType": asset.MediaType,
	})}
	if err := s.repository.UpdateAsset(ctx, asset, expectedStatus); err != nil {
		return command.Rejected(e, "MEDIA_UPDATE_FAILED", "INTERNAL", "SAFE_RETRY", "media.update_failed", nil)
	}
	return command.Accepted(e, "MediaAsset", asset.MediaAssetID, 1, "READY", eventRefs(domainEvents))
}

// ---------- ReviewMediaAsset (R15.17) ----------
// admin 手动 content review 路径。由 operator (PROXY_OPERATOR_PRINCIPALS)
// 调用。/v1/commands 层在 dispatch 前检 requiresOperator — 未设 env 或
// principal 不在白名单都被 OPERATOR_PRIVILEGE_REQUIRED 拒。
//
// allowed transitions:
//   - QUARANTINED → REJECTED_CONTENT_NUDITY / _POLITICS / _VIOLENCE
//   - APPROVED     → REJECTED_CONTENT_NUDITY / _POLITICS / _VIOLENCE
//                     (post-publish takedown, 不常见但需支持)
//   - REJECTED_CONTENT_* → APPROVED  (unblock)
//
// disallowed:
//   - REJECTED_TECHNICAL → 任何 CONTENT_*  (技术拒不可转内容拒, 保护 audit trail)
//   - FAILED / UPLOADING → CONTENT_*       (资产未完成处理不能走 content 门)
//   - CONTENT_* → CONTENT_* 不同类         (不双发 reject 同一 asset)
//
// audit trail: 写进 asset.LastError, 格式 'content-review:<reason>:<operator_id>'。
// 未来接 AI 内容审核会自动产生 review 事件, 在这里存原状。

type reviewMediaAssetPayload struct {
	// Reason — 取下列之一:
	//   "APPROVE"        (unblock)
	//   "REJECT_NUDITY"
	//   "REJECT_POLITICS"
	//   "REJECT_VIOLENCE"
	Reason string `json:"reason"`
	// Note — 人工 review 记录。可选, 但存 LastError 里帮 audit。
	Note string `json:"note"`
}

var reviewReasonToStatus = map[string]string{
	"APPROVE":         "APPROVED",
	"REJECT_NUDITY":   "REJECTED_CONTENT_NUDITY",
	"REJECT_POLITICS": "REJECTED_CONTENT_POLITICS",
	"REJECT_VIOLENCE": "REJECTED_CONTENT_VIOLENCE",
}

func (s *Service) reviewMediaAsset(ctx context.Context, e command.Envelope) command.Result {
	var p reviewMediaAssetPayload
	if !decode(e.Payload, &p) {
		return command.Rejected(e, "INVALID_REVIEW", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_review", nil)
	}
	target, ok := reviewReasonToStatus[p.Reason]
	if !ok {
		return command.Rejected(e, "INVALID_REVIEW_REASON", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_review_reason", map[string]any{"allowed": []string{"APPROVE", "REJECT_NUDITY", "REJECT_POLITICS", "REJECT_VIOLENCE"}})
	}
	asset, err := s.repository.GetAsset(ctx, e.Target.ID)
	if errors.Is(err, ErrAssetNotFound) {
		return command.Rejected(e, "MEDIA_ASSET_NOT_FOUND", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.asset_not_found", nil)
	}
	if err != nil {
		return command.Rejected(e, "MEDIA_READ_FAILED", "INTERNAL", "SAFE_RETRY", "media.read_failed", nil)
	}
	// disallowed transitions
	from := asset.ModerationStatus
	if from == "REJECTED_TECHNICAL" {
		return command.Rejected(e, "MEDIA_REVIEW_DISALLOWED", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.review_disallowed_technical", map[string]any{"from": from, "to": target})
	}
	if from == "UPLOADING" || from == "FAILED" || asset.ProcessingStatus == "UPLOADING" {
		return command.Rejected(e, "MEDIA_REVIEW_DISALLOWED", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.review_disallowed_incomplete", map[string]any{"processingStatus": asset.ProcessingStatus})
	}
	if from == target {
		return command.Rejected(e, "MEDIA_REVIEW_NOOP", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.review_noop", map[string]any{"status": from})
	}
	expectedStatus := asset.ProcessingStatus
	asset.ModerationStatus = target
	auditNote := "content-review:" + p.Reason + ":" + e.Principal.ID
	if p.Note != "" {
		auditNote = auditNote + ":" + p.Note
	}
	asset.LastError = auditNote
	asset.UpdatedAt = s.clock.Now().UTC()
	domainEvents := []event.DomainEvent{event.New("MediaAssetReviewed", "MediaAsset", asset.MediaAssetID, 1, e.Principal.ID, e.CorrelationID, e.CommandID, asset.UpdatedAt, map[string]any{
		"mediaAssetId": asset.MediaAssetID,
		"from":         from,
		"to":           target,
		"operatorId":   e.Principal.ID,
		"reason":       p.Reason,
		"note":         p.Note,
	})}
	if err := s.repository.UpdateAsset(ctx, asset, expectedStatus); err != nil {
		return command.Rejected(e, "MEDIA_UPDATE_FAILED", "INTERNAL", "SAFE_RETRY", "media.update_failed", nil)
	}
	// R15.18: 持久化决策行到 media_review_decisions 表 (memory / postgres)。
	// 失败不阻塞主命品 — audit 丢可重补, asset 状态已经定下。
	if s.reviewDecisionRepo != nil {
		decision := MediaReviewDecision{
			DecisionID:   "mrd_" + uuidHex(),
			MediaAssetID: asset.MediaAssetID,
			FromStatus:   from,
			ToStatus:     target,
			Reason:       p.Reason,
			Note:         p.Note,
			OperatorID:   e.Principal.ID,
			ReviewedAt:   asset.UpdatedAt,
		}
		if err := s.reviewDecisionRepo.AppendReviewDecision(ctx, decision); err != nil {
			// 软记录: 不返错, 只写入 result payload 的 audit warning
			domainEvents = append(domainEvents, event.New("MediaReviewDecisionPersistFailed", "MediaAsset", asset.MediaAssetID, 1, e.Principal.ID, e.CorrelationID, e.CommandID, s.clock.Now().UTC(), map[string]any{
				"mediaAssetId": asset.MediaAssetID,
				"reason":       err.Error(),
			}))
		}
	}
	return command.Accepted(e, "MediaAsset", asset.MediaAssetID, 1, target, eventRefs(domainEvents))
}

// ---------- GetMediaAsset / ListMediaAssets ----------
// 只能读自己名下的资产：storage key / URL 是敏感数据，不得跨 principal 泄露。

func (s *Service) getAsset(ctx context.Context, e command.Envelope) command.Result {
	assetID := e.Target.ID
	if assetID == "" {
		var p struct {
			MediaAssetID string `json:"mediaAssetId"`
		}
		if !decode(e.Payload, &p) || p.MediaAssetID == "" {
			return command.Rejected(e, "INVALID_ASSET_QUERY", "VALIDATION", "AFTER_USER_ACTION", "media.invalid_query", nil)
		}
		assetID = p.MediaAssetID
	}
	asset, err := s.repository.GetAsset(ctx, assetID)
	if errors.Is(err, ErrAssetNotFound) {
		return command.Rejected(e, "MEDIA_ASSET_NOT_FOUND", "BUSINESS_STATE", "AFTER_USER_ACTION", "media.asset_not_found", nil)
	}
	if err != nil {
		return command.Rejected(e, "MEDIA_READ_FAILED", "INTERNAL", "SAFE_RETRY", "media.read_failed", nil)
	}
	if asset.OwnerPrincipalID != e.Principal.ID {
		return command.Rejected(e, "MEDIA_NOT_OWNER", "AUTHORIZATION", "AFTER_USER_ACTION", "media.not_owner", nil)
	}
	return acceptedWithPayload(e, "MediaAsset", asset.MediaAssetID, 1, asset.ProcessingStatus, map[string]any{
		"asset":    asset,
		"playable": asset.ProcessingStatus == "READY", // 只有 READY 可正式播放
	}, nil)
}

