// Media P0（PRD Chapter06A §9-12）。
// 普通视频：upload / thumbnail / play / pause / seek / fullscreen / caption / share。
// 只有 READY 的视频允许正式播放。
// FFmpeg 不是播放器：客户端播 MP4/HLS URL；FFmpeg 负责把用户上传的
// HEVC/MOV/奇怪 rotation/不同音频 codec 标准化为 H.264+AAC MP4+faststart。
// 不做：多码率 HLS / ABR / 转码集群 / 直播 / WebRTC（P0 只要求正常播放）。

// MediaAsset 是媒体资产（IMAGE | VIDEO | AUDIO）。
type MediaAsset struct {
	MediaAssetID        string    `json:"mediaAssetId"`
	OwnerPrincipalType  string    `json:"ownerPrincipalType"`
	OwnerPrincipalID    string    `json:"ownerPrincipalId"`
	MediaType           string    `json:"mediaType"` // IMAGE | VIDEO | AUDIO
	OriginalStorageKey  string    `json:"originalStorageKey"`
	PlaybackStorageKey  string    `json:"playbackStorageKey,omitempty"`
	ThumbnailStorageKey string    `json:"thumbnailStorageKey,omitempty"`
	MimeType            string    `json:"mimeType,omitempty"`
	Width               int       `json:"width,omitempty"`
	Height              int       `json:"height,omitempty"`
	DurationMs          int64     `json:"durationMs,omitempty"`
	Codec               string    `json:"codec,omitempty"`
	ProcessingStatus    string    `json:"processingStatus"` // UPLOADING | PROCESSING | READY | FAILED
	PlaybackURL         string    `json:"playbackUrl,omitempty"`
	ThumbnailURL        string    `json:"thumbnailUrl,omitempty"`
	SourceBytes         int64     `json:"sourceBytes,omitempty"`
	ChecksumSHA256      string    `json:"checksumSha256,omitempty"`
	Orientation         int       `json:"orientation,omitempty"`
	ColorSpace          string    `json:"colorSpace,omitempty"`
	HasAlpha            bool      `json:"hasAlpha"`
	Animated            bool      `json:"animated"`
	ModerationStatus    string    `json:"moderationStatus"`
	VisibilityClass     string    `json:"visibilityClass"`
	// CompositionHint：主体类型 + 关键区域。P0 worker 可空，前端低置信度回落。
	CompositionHint           *MediaCompositionHint `json:"compositionHint,omitempty"`
	CompositionRecipeVersion  string                `json:"compositionRecipeVersion,omitempty"`
	CompositionComputedAt     *time.Time            `json:"compositionComputedAt,omitempty"`
	CompositionConfidence     float64               `json:"compositionConfidence,omitempty"`
	// DominantColorHex 主色（#RRGGBB），worker v1 派生后填。contain 模式下客户端
	// 用此色当 frame 背景，替代写死深紫黑 → 消除"图浅/背景深"的强对比灰边。
	// 失败填 DefaultDominantColor（#0E0A14）兑底。
	DominantColorHex string `json:"dominantColorHex,omitempty"`
	CreatedAt           time.Time `json:"createdAt"`
	UpdatedAt           time.Time `json:"updatedAt"`
	// LastError：确定性拒绝原因（如音频超 30s）。仅 FAILED 资产携带，供客户端展示。
	LastError string `json:"lastError,omitempty"`
	// R16.7-P1-K (LC-06) + R16.7-P1-I (LC-07): AI generation
	// provenance. AIGenerationSource is the single source of
	// truth for 'is this asset AI-generated?'; the boolean
	// AIGenerated is the convenience view. PRD v1.4 §4
	// (Vietnam 134/2025/QH15 Art. 12) requires every
	// AI-generated media asset to carry this label; the
	// platform must fail closed (refuse to publish) when the
	// source cannot be determined. The MarkMediaReady
	// handler is the gate.
	//
	// Source values:
	//   USER_UPLOADED  — captured by the device, no AI in the
	//                    loop. AIGenerated is false.
	//   AI_PERSONA     — produced by an AI persona
	//                    (aipersona.PersonaTypeUserTwin /
	//                    Creative). PersonaID and SubjectID
	//                    carry the linkage; LC-07 requires a
	//                    live likeness consent for USER_TWIN.
	//   MODEL_API      — generated by a third-party model API
	//                    (e.g. SD / Veo). No persona linkage.
	//   UNKNOWN        — the producer did not declare. Mark-
	//                    MediaReady rejects with
	//                    AI_LABEL_MISSING; this is the
	//                    fail-closed gate.
	AIGenerationSource string `json:"aiGenerationSource,omitempty"`
	AIGenerated        bool   `json:"aiGenerated"`
	// PersonaID is set when AIGenerationSource == AI_PERSONA.
	// For PersonaType == USER_TWIN, SubjectID is the real
	// person whose likeness is used; the persona service
	// looks up the live consent for (PersonaID, SubjectID).
	PersonaID string `json:"personaId,omitempty"`
	SubjectID string `json:"subjectId,omitempty"`
	// LikenessConsentID is stamped at MarkMediaReady time so
	// a regulator can recover 'this asset was published
	// under consent X'. Empty for non-AI / CREATIVE assets.
	LikenessConsentID string `json:"likenessConsentId,omitempty"`
}

// MediaVariant is an immutable, recipe-versioned representation for one UI purpose.
// ORIGINAL remains immutable; a recipe upgrade creates another row instead of overwriting it.
