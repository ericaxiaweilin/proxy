type MemoryRepository struct {
	mu       sync.Mutex
	assets   map[string]MediaAsset
	variants map[string]MediaVariant
	jobs     map[string]memoryProcessingJob
	events   []event.DomainEvent
}

type memoryProcessingJob struct {
	job    ProcessingJob
	worker string
}

func NewMemoryRepository() *MemoryRepository {
	return &MemoryRepository{assets: make(map[string]MediaAsset), variants: make(map[string]MediaVariant), jobs: make(map[string]memoryProcessingJob)}
}

func (r *MemoryRepository) CreateAsset(_ context.Context, a MediaAsset) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	if _, exists := r.assets[a.MediaAssetID]; exists {
		return errors.New("asset already exists")
	}
	r.assets[a.MediaAssetID] = a
	return nil
}

func (r *MemoryRepository) GetAsset(_ context.Context, id string) (MediaAsset, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	a, exists := r.assets[id]
	if !exists {
		return MediaAsset{}, ErrAssetNotFound
	}
	return a, nil
}

func (r *MemoryRepository) UpdateAsset(_ context.Context, a MediaAsset, expectedStatus string) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	current, exists := r.assets[a.MediaAssetID]
	if !exists {
		return ErrAssetNotFound
	}
	if current.ProcessingStatus != expectedStatus {
		return ErrStatusTransition
	}
	r.assets[a.MediaAssetID] = a
	return nil
}

func (r *MemoryRepository) UpdateCompositionHint(_ context.Context, assetID string, hint *MediaCompositionHint) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	asset, ok := r.assets[assetID]
	if !ok {
		return ErrAssetNotFound
	}
	// hint=nil 表示清空 (worker 调取失败后显式置 UNKNOWN)
	asset.CompositionHint = hint
	asset.UpdatedAt = time.Now().UTC()
	r.assets[assetID] = asset
	return nil
}

func (r *MemoryRepository) Snapshot(_ context.Context) ([]MediaAsset, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	result := make([]MediaAsset, 0, len(r.assets))
	for _, a := range r.assets {
		result = append(result, a)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].CreatedAt.After(result[j].CreatedAt) })
	return result, nil
}

func (r *MemoryRepository) UpsertVariant(_ context.Context, variant MediaVariant) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	key := variant.MediaAssetID + ":" + variant.Purpose + ":" + variant.RecipeVersion
	r.variants[key] = variant
	return nil
}

func (r *MemoryRepository) ListVariants(_ context.Context, mediaAssetID string) ([]MediaVariant, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	result := []MediaVariant{}
	for _, variant := range r.variants {
		if variant.MediaAssetID == mediaAssetID {
			result = append(result, variant)
		}
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Purpose < result[j].Purpose })
	return result, nil
}

func (r *MemoryRepository) GetVariant(_ context.Context, variantID string) (MediaVariant, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	for _, variant := range r.variants {
		if variant.MediaVariantID == variantID {
			return variant, nil
		}
	}
	return MediaVariant{}, ErrAssetNotFound
}

type Service struct {
	mu                   sync.Mutex
	repository           Repository
	reviewDecisionRepo   ReviewDecisionRepository
	processor            Processor
	clock                clock.Clock
	storeDir             string
	logger               *log.Logger
	// personaService is the LC-07 likeness-consent
	// reader. Wired from cmd/api/main.go. nil means the
	// legacy test server is in use; markReady falls back to
	// a permissive path so existing tests pass. Production
	// deployments must wire it.
	personaService *aipersona.Service
}

func New() *Service {
	return NewWithReviewDecisionRepository(NewMemoryRepository(), NewMemoryReviewDecisionRepository(), nil)
}

// NewWithDependencies 注入 repository 和 processor。
// processor 为 nil 时用 NoopProcessor（单测/无 ffmpeg 环境）。
// reviewDecisionRepo 为 nil 时用 MemoryReviewDecisionRepository,
// 是默认 (R15.18 让 memory 模式也能 持久化决策)。
func NewWithDependencies(repository Repository, processor Processor) *Service {
	return NewWithReviewDecisionRepository(repository, NewMemoryReviewDecisionRepository(), processor)
}

// NewWithReviewDecisionRepository R15.18 入口: 注入决策仓库。
func NewWithReviewDecisionRepository(repository Repository, reviewDecisionRepo ReviewDecisionRepository, processor Processor) *Service {
	if repository == nil {
		repository = NewMemoryRepository()
	}
	if reviewDecisionRepo == nil {
		reviewDecisionRepo = NewMemoryReviewDecisionRepository()
	}
	return &Service{repository: repository, reviewDecisionRepo: reviewDecisionRepo, processor: processor, clock: clock.System{}, storeDir: filepath.Join(".", "media_store")}
}

// SetStoreDir 覆盖媒体文件本地目录（与 FFmpegProcessor.StoreDir 对齐）。
